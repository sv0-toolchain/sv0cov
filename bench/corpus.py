# --- materialization and the manifest --------------------------------------------------------


def tree_digest(files: dict[str, bytes]) -> str:
    listing = [{"path": p, "sha256": hashlib.sha256(files[p]).hexdigest(), "size": len(files[p])} for p in sorted(files, key=str.encode)]
    return hashlib.sha256(encode(listing)).hexdigest()


def materialize_one(f: Fixture) -> tuple[dict[str, bytes], Program | None]:
    made = f.make()
    if made is None:
        return {}, None
    if isinstance(made, Program):
        return made.files, made
    return made, None


def manifest_entry(f: Fixture, *, heavy: bool) -> dict:
    heavy_fixture = f.category == "merge-report-scale"
    files, prog = materialize_one(f) if (heavy or not heavy_fixture) else ({}, None)
    entry = {
        "applicable_budgets": sorted(f.budgets),
        "backends": f.backends,
        "category": f.category,
        "contract_mode": f.contract_mode,
        "coverage_modes": ["off", "instrument"],
        "id": f.id,
        "purpose": f.purpose,
        "source": f.source,
        "status": f.status,
        "timed_boundary": f.boundary,
        "weight": "equal",
    }
    if prog is not None:
        entry["expected"] = {"exit_code": prog.exit_code, "stdout_sha256": EMPTY_STDOUT}
        entry["scale"] = prog.facts
        entry["build"] = {"entry": prog.entry, "mode": "project" if prog.entry == "." else "file"}
    if files:
        entry["tree_sha256"] = tree_digest(files)
        entry["files"] = len(files)
    return entry


def build_manifest(*, heavy: bool = False, previous: dict | None = None) -> dict:
    entries = []
    prev = {e["id"]: e for e in (previous or {}).get("fixtures", [])}
    for f in fixtures():
        e = manifest_entry(f, heavy=heavy)
        if not heavy and f.category == "merge-report-scale" and f.id in prev:
            for k in ("tree_sha256", "files"):  # full-scale digests are recorded by `write --heavy` and checked by replay
                if k in prev[f.id]:
                    e[k] = prev[f.id][k]
        entries.append(e)
    return {
        "categories": list(CATEGORIES),
        "corpus_version": CORPUS_VERSION,
        "fixtures": entries,
        "generator": GENERATOR,
        "schema": "sv0cov.benchmark-corpus",
        "snapshots": {k: {"copyright": v["copyright"], "license": v["license"], "repository": v["repository"], "revision": v["revision"],
                          "files": {p: hashlib.sha256((REAL / k / p).read_bytes()).hexdigest() for p in v["paths"]}} for k, v in SNAPSHOTS.items()},
        "version": "1.0",
    }


def check_manifest_object(m: dict) -> None:
    ids = [f["id"] for f in m["fixtures"]]
    if len(set(ids)) != len(ids):
        raise ValueError("fixture ids must be unique")
    for cat in CATEGORIES:
        members = [f for f in m["fixtures"] if f["category"] == cat]
        if len(members) < 3:
            raise ValueError(f"category {cat} has fewer than three fixtures")
    if {f["category"] for f in m["fixtures"]} != set(CATEGORIES):
        raise ValueError("fixtures use a category outside the ten")
    for f in m["fixtures"]:
        if f["weight"] != "equal":
            raise ValueError(f"{f['id']}: weighting exceptions need a recorded reason")
        if f["status"] == "runnable-baseline" and ("expected" not in f or "tree_sha256" not in f):
            raise ValueError(f"{f['id']}: a runnable fixture needs an expected result and a tree digest")


def write_tree(files: dict[str, bytes], target: Path) -> None:
    for rel, data in files.items():
        p = target / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)


# --- run plans ------------------------------------------------------------------------------


def plan(toolchain: Path, work: Path, dimension: str, ids: list[str] | None) -> dict:
    """Bind runnable fixtures to coverage-off commands (the only arm that exists yet)."""
    sv0 = str(toolchain / "scripts" / "sv0")
    recorded = {f["id"]: f for f in json.loads(MANIFEST.read_bytes())["fixtures"]}
    out = []
    for f in fixtures():
        if ids and f.id not in ids:
            continue
        if f.status != "runnable-baseline" and not (dimension == "ingest" and f.category == "merge-report-scale"):
            continue
        files, prog = materialize_one(f)
        want = recorded.get(f.id, {}).get("tree_sha256")
        if want is not None and tree_digest(files) != want:
            raise SystemExit(f"{f.id}: replay digest {tree_digest(files)} differs from the manifest's {want}")
        src = work / f.id
        write_tree(files, src)
        if dimension == "ingest":
            if f.category != "merge-report-scale":
                continue
            argv = [os.path.realpath(sys.executable), "-I", "-B", str(BENCH / "ingest.py"), str(src)]
            out.append({"arms": {"off": {"argv": argv, "expect": {"exit_code": 0, "stdout_sha256": None}}, "on": None},
                        "category": f.category, "cwd": str(src), "id": f"{f.id}/ingest"})
            continue
        if prog is None or "native" not in f.backends:
            continue
        exe = work / f"{f.id}.exe"
        target = ["--project", str(src)] if prog.entry == "." else [str(src / prog.entry)]
        compile_argv = [sv0, "native-compile", "-o", str(exe), *target]
        if dimension == "compile":
            argv, expect = compile_argv, {"exit_code": 0, "stdout_sha256": None}
        else:
            subprocess.run(compile_argv, check=True, capture_output=True)
            argv, expect = [str(exe)], {"exit_code": prog.exit_code, "stdout_sha256": EMPTY_STDOUT}
        out.append({"arms": {"off": {"argv": argv, "expect": expect}, "on": None}, "category": f.category, "cwd": str(work), "id": f"{f.id}/{dimension}"})
    return {"corpus": {"generator": GENERATOR, "manifest_sha256": hashlib.sha256(MANIFEST.read_bytes()).hexdigest(), "version": CORPUS_VERSION}, "fixtures": out}


def refresh_snapshots(toolchain: Path) -> None:
    for name, s in SNAPSHOTS.items():
        checkout = toolchain / SNAPSHOT_CHECKOUTS[s["repository"]]
        for p in s["paths"]:
            data = subprocess.run(["git", "show", f"{s['revision']}:{p}"], cwd=checkout, check=True, capture_output=True).stdout
            target = REAL / name / p
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    w = sub.add_parser("write")
    w.add_argument("--heavy", action="store_true", help="also materialize the merge/report-scale fixtures and record their digests")
    m = sub.add_parser("materialize")
    m.add_argument("dir", type=Path)
    m.add_argument("--id", action="append")
    pl = sub.add_parser("plan")
    pl.add_argument("--toolchain", type=Path)
    pl.add_argument("--work", type=Path, required=True)
    pl.add_argument("--dimension", choices=("compile", "execute", "ingest"), required=True)
    pl.add_argument("--id", action="append")
    rs = sub.add_parser("refresh-snapshots")
    rs.add_argument("--toolchain", type=Path, required=True)
    args = ap.parse_args()
    if args.cmd == "refresh-snapshots":
        refresh_snapshots(args.toolchain.resolve())
        return 0
    if args.cmd == "write":
        previous = json.loads(MANIFEST.read_bytes()) if MANIFEST.is_file() else None
        m_obj = build_manifest(heavy=args.heavy, previous=previous)
        check_manifest_object(m_obj)
        MANIFEST.write_bytes(encode(m_obj))
        print(f"corpus manifest: wrote {len(m_obj['fixtures'])} fixtures")
        return 0
    if args.cmd == "check":
        current = json.loads(MANIFEST.read_bytes())
        m_obj = build_manifest(previous=current)
        check_manifest_object(m_obj)
        if encode(m_obj) != MANIFEST.read_bytes():
            print("corpus manifest is stale or a snapshot changed", file=sys.stderr)
            return 1
        print("corpus manifest: current")
        return 0
    if args.cmd == "materialize":
        for f in fixtures():
            if args.id and f.id not in args.id:
                continue
            files, _ = materialize_one(f)
            write_tree(files, args.dir / f.id)
            print(f"{f.id}: {tree_digest(files) if files else 'nothing to materialize'}")
        return 0
    work = args.work.resolve()
    work.mkdir(parents=True, exist_ok=True)
    sys.stdout.buffer.write(encode(plan((args.toolchain or ROOT).resolve(), work, args.dimension, args.id)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
