@dataclass
class Fixture:
    id: str
    category: str
    purpose: str
    source: dict
    make: object  # () -> Program | dict[str, bytes] | None
    budgets: list[str] = field(default_factory=lambda: list(BUDGETS_BUILD_RUN))
    backends: list[str] = field(default_factory=lambda: ["native", "vm-v1"])
    status: str = "runnable-baseline"
    contract_mode: str = "runtime"
    boundary: dict = field(default_factory=lambda: {
        "compile": "driver invocation through a written executable or .sv0b; excludes corpus materialization",
        "execute": "process spawn through reaped exit of the built program; excludes the build",
    })


def _gen(name: str, seed: int, **params) -> dict:
    return {"generator": GENERATOR, "kind": "generated", "name": name, "params": params, "seed": seed}


def _snap(snapshot: str, paths: list[str], entry: str) -> dict:
    s = SNAPSHOTS[snapshot]
    return {"entry": entry, "kind": "snapshot", "paths": paths, "repository": s["repository"], "revision": s["revision"], "snapshot": snapshot}


def lexical_facts(files: dict[str, bytes]) -> dict:
    """Scale facts for real sources by lexical scan (comments and strings removed).

    An estimate until the planner (CV-107..110) can report exact counts.
    """
    text = "\n".join(re.sub(r'"(?:\\.|[^"\\])*"', '""', re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", v.decode(), flags=re.S))) for v in files.values())
    fns = len(re.findall(r"\bfn\s+\w+\s*\(", text))
    ifs = len(re.findall(r"\bif\b", text))
    loops = len(re.findall(r"\bwhile\b", text))
    arms = len(re.findall(r"=>", text))
    matches = len(re.findall(r"\bmatch\b", text))
    contracts = len(re.findall(r"\b(?:requires|ensures)\s*\(", text))
    facts = _facts(fns, ifs, loops, arms, contracts=contracts, short_circuit=len(re.findall(r"&&|\|\|", text)), files=len(files), matches=matches)
    facts["method"] = "lexical-estimate"
    return facts


def _snapshot_program(snapshot: str, paths: list[str], entry: str, exit_code: int, facts: dict) -> Program:
    files = snapshot_files(snapshot, paths)
    facts = lexical_facts(files)
    if entry == ".":  # a project: the entry test file becomes main.sv0 next to lib/
        test = next(p for p in paths if p.startswith("test/"))
        files = {("main.sv0" if p == test else p): v for p, v in files.items()}
    return Program(files, entry if entry == "." else paths[0], exit_code, facts)


