# --- deterministic randomness ------------------------------------------------


class SplitMix64:
    """Pinned PRNG (independent of Python's ``random`` implementation)."""

    def __init__(self, seed: int) -> None:
        self.state = seed & 0xFFFFFFFFFFFFFFFF

    def next(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & 0xFFFFFFFFFFFFFFFF
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & 0xFFFFFFFFFFFFFFFF
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & 0xFFFFFFFFFFFFFFFF
        return z ^ (z >> 31)

    def below(self, n: int) -> int:
        return self.next() % n


# --- programs ------------------------------------------------------------------


@dataclass
class Program:
    files: dict[str, bytes]
    entry: str  # a file (single-file build) or "." (project build)
    exit_code: int
    facts: dict = field(default_factory=dict)


def _facts(functions: int, ifs: int = 0, loops: int = 0, arms: int = 0, contracts: int = 0, short_circuit: int = 0, files: int = 1, matches: int = 0) -> dict:
    return {
        "branches": ifs + loops + matches,
        "contracts": contracts,
        "functions": functions,
        "if_statements": ifs,
        "loops": loops,
        "match_arms": arms,
        "planned_counters_f0": functions + 2 * ifs + 2 * loops + arms,
        "short_circuit_operators": short_circuit,
        "source_files": files,
    }


def _one(gen: str, body: str, exit_code: int, facts: dict) -> Program:
    return Program({"main.sv0": (HEADER.format(gen=gen) + body).encode()}, "main.sv0", exit_code, facts)


def _finish_main(lines: list[str], acc_value: int) -> str:
    return "fn main() -> i32 {\n  let mut acc = 0;\n" + "".join(lines) + f"  return acc - {acc_value};\n}}\n"


def gen_startup(variant: str, seed: int) -> Program:
    r = SplitMix64(seed)
    if variant == "empty":
        return _one("startup/empty", "\nfn main() -> i32 {\n  return 0;\n}\n", 0, _facts(1))
    n = {"cli": 5, "multi": 20}[variant]
    out, calls, acc = [], [], 0
    for i in range(n):
        a, b, arg = r.below(900) + 2, r.below(1000), r.below(1000)
        out.append(f"\nfn step{i}(x: i32) -> i32 {{\n  return (x * {a} + {b}) % {MOD};\n}}\n")
        calls.append(f"  acc = (acc + step{i}({arg})) % {MOD};\n")
        acc = (acc + (arg * a + b) % MOD) % MOD
    return _one(f"startup/{variant}", "".join(out) + "\n" + _finish_main(calls, acc), 0, _facts(n + 1))


def gen_straight(functions: int, statements: int, seed: int) -> Program:
    r = SplitMix64(seed)
    out, calls, acc = [], [], 0
    for i in range(functions):
        lines, x0 = [], r.below(MOD)
        x = x0
        for _ in range(statements):
            a, b = r.below(900) + 2, r.below(MOD)
            lines.append(f"  x = (x * {a} + {b}) % {MOD};\n")
            x = (x * a + b) % MOD
        out.append(f"\nfn f{i}(x0: i32) -> i32 {{\n  let mut x = x0;\n" + "".join(lines) + "  return x;\n}\n")
        calls.append(f"  acc = (acc + f{i}({x0})) % {MOD};\n")
        acc = (acc + x) % MOD
    return _one(f"straight/{functions}x{statements}", "".join(out) + "\n" + _finish_main(calls, acc), 0, _facts(functions + 1))


def gen_decisions(variant: str, count: int, seed: int) -> Program:
    r = SplitMix64(seed)
    out, calls, acc = [], [], 0
    ifs = loops = arms = sc = 0
    for i in range(count):
        arg = r.below(10000)
        if variant == "if-flat":
            k = 8
            body, y = "", 0
            for _ in range(k):
                m, c = r.below(7) + 2, r.below(50) + 1
                rem = r.below(m)
                body += f"  if x % {m} == {rem} {{\n    y = y + {c};\n  }};\n"
                if arg % m == rem:
                    y += c
            ifs += k
            out.append(f"\nfn d{i}(x: i32) -> i32 {{\n  let mut y = 0;\n{body}  return y;\n}}\n")
        elif variant == "if-nested":
            depth = 6
            body, close, y, live, ind = "", "", 0, True, "  "
            for _ in range(depth):
                m, c = r.below(3) + 2, r.below(50) + 1
                body += f"{ind}if x % {m} != 0 {{\n{ind}  y = y + {c};\n"
                close = f"{ind}}};\n" + close
                live = live and arg % m != 0
                if live:
                    y += c
                ind += "  "
            ifs += depth
            out.append(f"\nfn d{i}(x: i32) -> i32 {{\n  let mut y = 0;\n{body}{close}  return y;\n}}\n")
        elif variant == "loops":
            n, k, c = r.below(40) + 10, r.below(5) + 2, r.below(90) + 1
            s = 0
            for j in range(1, n + 1):
                if j % k == 0:
                    continue
                s = (s + j * c) % MOD
            out.append(
                f"\nfn d{i}(x: i32) -> i32 {{\n  let mut s = 0;\n  let mut j = 0;\n  while j < {n} {{\n    j = j + 1;\n"
                f"    if j % {k} == 0 {{\n      continue;\n    }};\n    s = (s + j * {c}) % {MOD};\n  }};\n  return s + x - x;\n}}\n"
            )
            loops += 1
            ifs += 1
            y = s
        elif variant == "match":
            k = 8
            vals = [r.below(1000) for _ in range(k + 1)]
            cases = "".join(f"    {j} => {vals[j]},\n" for j in range(k))
            out.append(f"\nfn d{i}(x: i32) -> i32 {{\n  let key = x % {k + 3};\n  return match key {{\n{cases}    _ => {vals[k]},\n  }};\n}}\n")
            key = arg % (k + 3)
            y = vals[key] if key < k else vals[k]
            arms += k + 1
        elif variant == "short-circuit":
            a, b, c, d = r.below(5) + 2, r.below(5) + 2, r.below(9000), r.below(7) + 2
            y = 0
            out.append(
                f"\nfn d{i}(x: i32) -> i32 {{\n  let mut y = 0;\n  if x % {a} == 0 && x % {b} != 0 {{\n    y = y + 1;\n  }};\n"
                f"  if x > {c} || x % {d} == 1 {{\n    y = y + 2;\n  }};\n  return y;\n}}\n"
            )
            if arg % a == 0 and arg % b != 0:
                y += 1
            if arg > c or arg % d == 1:
                y += 2
            ifs += 2
            sc += 2
        else:
            raise ValueError(variant)
        calls.append(f"  acc = (acc + d{i}({arg})) % {MOD};\n")
        acc = (acc + y) % MOD
    facts = _facts(count + 1, ifs, loops, arms, short_circuit=sc, matches=count if variant == "match" else 0)
    return _one(f"decisions/{variant}", "".join(out) + "\n" + _finish_main(calls, acc), 0, facts)


def gen_contracts(variant: str, count: int, seed: int) -> Program:
    r = SplitMix64(seed)
    out, calls, acc = [], [], 0
    contracts = 0
    for i in range(count):
        lo, c, arg = r.below(50), r.below(90) + 2, r.below(1000) + 100
        checked = variant != "mixed" or i % 2 == 0
        pre = f" requires(x >= {lo}) ensures(true)" if checked else ""
        contracts += 2 if checked else 0
        out.append(f"\nfn g{i}(x: i32) -> i32{pre} {{\n  return (x * {c}) % {MOD};\n}}\n")
        calls.append(f"  acc = (acc + g{i}({arg})) % {MOD};\n")
        acc = (acc + arg * c % MOD) % MOD
    exit_code = 0
    if variant == "failing":
        calls.append("  acc = acc + g0(0 - 1);\n")
        exit_code = 1
    return _one(f"contracts/{variant}", "".join(out) + "\n" + _finish_main(calls, acc), exit_code, _facts(count + 1, contracts=contracts))


def gen_modules(variant: str, count: int, seed: int) -> Program:
    r = SplitMix64(seed)
    files, uses, calls, acc = {}, [], [], 0
    for i in range(count):
        name = f"m{i}"
        path = {"many-files": f"{name}/{name}.sv0", "shared-deps": f"{name}/{name}.sv0", "same-basename": f"{name}/util.sv0"}[variant]
        a, arg = r.below(900) + 2, r.below(1000)
        dep = ""
        if variant == "shared-deps":
            dep = "use common::base;\n\n"
            body = f"  return (base(x) * {a}) % {MOD};\n"
            val = ((arg + 7) * a) % MOD
        else:
            body = f"  return (x * {a}) % {MOD};\n"
            val = (arg * a) % MOD
        files[path] = (HEADER.format(gen=f"modules/{variant}") + f"module {name};\n\n{dep}fn f{name}(x: i32) -> i32 {{\n{body}}}\n").encode()
        uses.append(f"use {name}::f{name};\n")
        calls.append(f"  acc = (acc + f{name}({arg})) % {MOD};\n")
        acc = (acc + val) % MOD
    functions = count + 1
    if variant == "shared-deps":
        files["common/common.sv0"] = (HEADER.format(gen="modules/shared-deps") + "module common;\n\nfn base(x: i32) -> i32 {\n  return x + 7;\n}\n").encode()
        functions += 1
    main = HEADER.format(gen=f"modules/{variant}") + "".join(uses) + "\n" + _finish_main(calls, acc)
    files["main.sv0"] = main.encode()
    return Program(files, ".", 0, _facts(functions, files=len(files)))


def gen_vm(variant: str, iterations: int, seed: int) -> Program:
    r = SplitMix64(seed)
    a, b = r.below(900) + 2, r.below(1000)
    if variant == "arith":
        x = 1
        for _ in range(iterations):
            x = (x * a + b) % MOD
        body = f"\nfn main() -> i32 {{\n  let mut x = 1;\n  let mut i = 0;\n  while i < {iterations} {{\n    x = (x * {a} + {b}) % {MOD};\n    i = i + 1;\n  }};\n  return x - {x};\n}}\n"
        return _one("vm/arith", body, 0, _facts(1, loops=1))
    if variant == "branchy":
        s = 0
        for i in range(iterations):
            s = (s + (a if i % 3 == 0 else b if i % 3 == 1 else 1)) % MOD
        body = (
            f"\nfn main() -> i32 {{\n  let mut s = 0;\n  let mut i = 0;\n  while i < {iterations} {{\n"
            f"    if i % 3 == 0 {{\n      s = (s + {a}) % {MOD};\n    }} else {{\n      if i % 3 == 1 {{\n        s = (s + {b}) % {MOD};\n"
            f"      }} else {{\n        s = (s + 1) % {MOD};\n      }};\n    }};\n    i = i + 1;\n  }};\n  return s - {s};\n}}\n"
        )
        return _one("vm/branchy", body, 0, _facts(1, ifs=2, loops=1))
    if variant == "calls":
        x = 0
        for i in range(iterations):
            x = (x + (i * a + b) % MOD) % MOD
        body = (
            f"\nfn h(i: i32) -> i32 {{\n  return (i * {a} + {b}) % {MOD};\n}}\n\nfn main() -> i32 {{\n  let mut x = 0;\n  let mut i = 0;\n"
            f"  while i < {iterations} {{\n    x = (x + h(i)) % {MOD};\n    i = i + 1;\n  }};\n  return x - {x};\n}}\n"
        )
        return _one("vm/calls", body, 0, _facts(2, loops=1))
    raise ValueError(variant)


# --- merge/report scale artifacts ---------------------------------------------------


@functools.lru_cache(maxsize=2)
def _scale_map(points: int) -> tuple[bytes, bytes, str, int]:
    """(source, canonical map bytes, map id, counter count) for ``points``; shared by the scale fixtures."""
    out = _build_scale_map(points)
    return out


def gen_scale(points: int, profiles: int, seed: int) -> dict[str, bytes]:
    from sv0cov.formats import rawprofile as RP

    source, data, map_id, n = _scale_map(points)
    r = SplitMix64(seed)
    out = {"scale.sv0": source, "scale.sv0covmap.json": data}
    for k in range(profiles):
        counts = tuple((i, c) for i in range(n) if (c := r.below(1000)) > 0)
        profile = RP.RawProfile(bytes.fromhex(map_id), bytes([0xA0 + k]) * 16, bytes([k + 1]) * 16, "native", None, counts)
        out[f"profile-{k}.sv0profraw"] = RP.encode(profile, n)
    return out


def _build_scale_map(points: int) -> tuple[bytes, bytes, str, int]:
    """A canonical map with ``points`` counted points and ``profiles`` raw profiles.

    Each synthetic function contributes an entry and an ``if`` (three points)
    and two regions. Built with the reviewed semantic-fixture planner, with its
    line index cached so construction stays linear.
    """
    sys.path.insert(0, str(ROOT / "tests" / "fixtures" / "semantic"))
    import plan as P  # noqa: PLC0415 - dev-only dependency on the fixture planner

    from sv0cov.formats import map as M

    functions = -(-points // 3)
    chunks, spans = [HEADER.format(gen=f"scale/{points}")], []
    offset = len(chunks[0].encode())
    for i in range(functions):
        text = f"\nfn f{i}(n: i32) -> i32 {{\n  if n > {i} {{\n    return 1;\n  }};\n  return 0;\n}}\n"
        start = offset + 1
        fn_end = offset + len(text) - 1
        if_at = start + text.index("if n") - 1
        cond = (if_at + 3, if_at + 3 + len(f"n > {i}"))
        block_start = text.index("{\n    return") - 1 + start
        block_end = block_start + len("{\n    return 1;\n  }")
        ret1 = text.index("return 1;") - 1 + start
        ret0 = text.index("return 0;") - 1 + start
        spans.append((start, fn_end, if_at, block_end, cond, (block_start, block_end), (ret1, ret1 + 9), (ret0, ret0 + 9)))
        chunks.append(text)
        offset += len(text)
    source = "".join(chunks).encode()
    path = "scale.sv0"
    cache: dict[int, object] = {}
    original = P._Text

    def cached(data: bytes):
        if id(data) not in cache:
            cache[id(data)] = original(data)
        return cache[id(data)]

    P._Text = cached
    P.validate_map = functools.partial(M.validate_map, limits=SCALE_LIMITS)
    try:
        p = P.Plan(f"scale-{points}", {path: source})
        for i, (start, end, if_at, if_end, cond, block, ret1, ret0) in enumerate(spans):
            fn = P.Function(path, f"f{i}", (start, end))
            fn.entry = P.Point(path, fn, "function_entry", (start, end), "entry", label=f"f{i}.entry")
            p.functions.append(fn)
            br = p.branch(fn, "if", (if_at, if_end))
            p.region(fn, "branch_body", block, br["true"], lc=False)
            p.region(fn, "return", ret1, br["true"])
            p.region(fn, "return", ret0, fn.entry, (br["true"], -1))
        m = p.build()
    finally:
        P._Text = original
        P.validate_map = M.validate_map
    data = encode(m)
    M.validate_map(data, sources={path: source}, limits=SCALE_LIMITS)
    return source, data, m["map_id"], m["program_counter_count"]


